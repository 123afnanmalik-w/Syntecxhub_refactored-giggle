from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# ---------------- CONFIGURATION ----------------

HOST = "127.0.0.1"
PORT = 5055

# Demo key for this notebook only.
# In a real application, use secure key exchange.
SHARED_SECRET = os.urandom(32)
KEY = hashlib.sha256(SHARED_SECRET).digest()
aes = AESGCM(KEY)

server_running = threading.Event()
server_running.set()

clients = []
clients_lock = threading.Lock()
log_lock = threading.Lock()
output_lock = threading.Lock()

LOG_FILE = "encrypted_chat.log"


# ---------------- ENCRYPTION ----------------

def encrypt_message(message):
    nonce = os.urandom(12)
    ciphertext = aes.encrypt(
        nonce,
        message.encode("utf-8"),
        None
    )

    # Store nonce together with ciphertext.
    combined = nonce + ciphertext
    return base64.b64encode(combined).decode("ascii")


def decrypt_message(encoded_message):
    combined = base64.b64decode(
        encoded_message,
        validate=True
    )

    if len(combined) < 28:
        raise ValueError("Invalid encrypted message")

    nonce = combined[:12]
    ciphertext = combined[12:]

    plaintext = aes.decrypt(nonce, ciphertext, None)
    return plaintext.decode("utf-8")


# ---------------- ENCRYPTED MESSAGE LOGGING ----------------

def save_encrypted_log(encoded_message):
    with log_lock:
        with open(LOG_FILE, "a", encoding="utf-8") as file:
            file.write(
                datetime.now().isoformat()
                + " | "
                + encoded_message
                + "\n"
            )


# ---------------- SERVER ----------------

def remove_client(conn):
    with clients_lock:
        if conn in clients:
            clients.remove(conn)

    try:
        conn.close()
    except OSError:
        pass


def broadcast(packet, sender):
    encoded_packet = (
        json.dumps(packet) + "\n"
    ).encode("utf-8")

    with clients_lock:
        recipients = [
            client for client in clients
            if client is not sender
        ]

    for client in recipients:
        try:
            client.sendall(encoded_packet)
        except OSError:
            remove_client(client)


def handle_client(conn, address):
    buffer = b""

    try:
        while server_running.is_set():
            chunk = conn.recv(4096)

            if not chunk:
                break

            buffer += chunk

            while b"\n" in buffer:
                line, buffer = buffer.split(b"\n", 1)

                if not line:
                    continue

                try:
                    packet = json.loads(line.decode("utf-8"))

                    if packet.get("type") != "message":
                        continue

                    encrypted = packet.get("data", "")
                    if not isinstance(encrypted, str):
                        continue

                    # Validate the encrypted payload format.
                    base64.b64decode(encrypted, validate=True)

                    # Server saves ciphertext, not plaintext.
                    save_encrypted_log(encrypted)

                    # Forward encrypted message to other clients.
                    broadcast(packet, conn)

                except (ValueError, json.JSONDecodeError,
                        UnicodeDecodeError):
                    print("Server rejected an invalid packet.")

    except OSError:
        pass
    finally:
        remove_client(conn)


def start_server():
    server = socket.socket(
        socket.AF_INET,
        socket.SOCK_STREAM
    )
    server.setsockopt(
        socket.SOL_SOCKET,
        socket.SO_REUSEADDR,
        1
    )

    try:
        server.bind((HOST, PORT))
        server.listen()
        server.settimeout(1)

        print(f"Server running on {HOST}:{PORT}")

        while server_running.is_set():
            try:
                conn, address = server.accept()
            except socket.timeout:
                continue

            with clients_lock:
                clients.append(conn)

            thread = threading.Thread(
                target=handle_client,
                args=(conn, address),
                daemon=True
            )
            thread.start()

    finally:
        server.close()


# ---------------- CHAT CLIENT ----------------

class ChatClient:
    def __init__(self, name):
        self.name = name
        self.sock = socket.socket(
            socket.AF_INET,
            socket.SOCK_STREAM
        )
        self.received_messages = []
        self.receive_lock = threading.Lock()
        self.sock.connect((HOST, PORT))

        self.receiver = threading.Thread(
            target=self.receive_loop,
            daemon=True
        )
        self.receiver.start()

    def send_message(self, message):
        encrypted = encrypt_message(message)

        packet = {
            "type": "message",
            "name": self.name,
            "data": encrypted
        }

        data = (
            json.dumps(packet) + "\n"
        ).encode("utf-8")

        self.sock.sendall(data)

        print(f"\n{self.name} sends: {message}")
        print(f"Encrypted data: {encrypted[:45]}...")

    def receive_loop(self):
        buffer = b""

        try:
            while True:
                chunk = self.sock.recv(4096)

                if not chunk:
                    break

                buffer += chunk

                while b"\n" in buffer:
                    line, buffer = buffer.split(b"\n", 1)

                    if not line:
                        continue

                    packet = json.loads(line.decode("utf-8"))

                    if packet.get("type") == "message":
                        try:
                            plaintext = decrypt_message(
                                packet["data"]
                            )

                            item = (
                                packet.get("name", "User"),
                                plaintext
                            )

                            with self.receive_lock:
                                self.received_messages.append(item)

                        except Exception:
                            print("Message could not be decrypted.")

        except (OSError, ValueError, json.JSONDecodeError):
            pass

    def close(self):
        try:
            self.sock.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass

        self.sock.close()


